import Foundation
import NotchGateKit
import Testing
@testable import NotchGate

@Suite("Resume widget")
struct ResumeWidgetTests {
    private let now = Date(timeIntervalSince1970: 1_800_000_000)

    // MARK: Fixtures

    /// A fresh `projects` folder, deleted when the test's scope ends.
    private final class Projects {
        let root: URL
        let workspace: URL

        init() throws {
            let base = FileManager.default.temporaryDirectory.appendingPathComponent("resume-tests-\(UUID().uuidString)")
            root = base.appendingPathComponent("projects")
            workspace = base.appendingPathComponent("workspace")
            try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
            try FileManager.default.createDirectory(at: workspace, withIntermediateDirectories: true)
        }

        deinit { try? FileManager.default.removeItem(at: root.deletingLastPathComponent()) }

        @discardableResult
        func transcript(_ id: String, project: String = "-tmp-shop", lines: [String], modified: Date) throws -> URL {
            let folder = root.appendingPathComponent(project)
            try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
            let url = folder.appendingPathComponent("\(id).jsonl")
            try (lines.joined(separator: "\n") + "\n").write(to: url, atomically: true, encoding: .utf8)
            try FileManager.default.setAttributes([.modificationDate: modified], ofItemAtPath: url.path)
            return url
        }
    }

    private func json(_ object: [String: Any]) -> String {
        let data = try! JSONSerialization.data(withJSONObject: object, options: [.sortedKeys])
        return String(decoding: data, as: UTF8.self)
    }

    private func user(_ text: Any, cwd: String = "/tmp/shop", branch: String = "main", extra: [String: Any] = [:]) -> String {
        json(["type": "user", "cwd": cwd, "gitBranch": branch, "entrypoint": "cli", "message": ["role": "user", "content": text]]
            .merging(extra) { $1 })
    }

    private func assistant(cwd: String = "/tmp/shop", branch: String = "main") -> String {
        json(["type": "assistant", "cwd": cwd, "gitBranch": branch, "message": ["role": "assistant", "content": [["type": "text", "text": "Done"]]]])
    }

    private func lines(_ strings: [String]) -> [Data] { strings.map { Data($0.utf8) } }

    // MARK: Parsing

    @Test func titlePrefersRenameThenClaudesTitleThenFirstPrompt() {
        var details = SessionHistory.scan(lines([user("fix the login bug"), assistant()]))
        #expect(details.title == "fix the login bug")

        details = SessionHistory.scan(lines([
            user("fix the login bug"), assistant(),
            json(["type": "ai-title", "aiTitle": "Login fix"]),
            json(["type": "ai-title", "aiTitle": "Login and signup fix"]),
        ]))
        #expect(details.title == "Login and signup fix")

        details = SessionHistory.scan(lines([
            user("fix the login bug"), json(["type": "ai-title", "aiTitle": "Login fix"]),
            json(["type": "custom-title", "customTitle": "Auth work"]),
        ]))
        #expect(details.title == "Auth work")
    }

    @Test func skipsGeneratedUserMessages() {
        let details = SessionHistory.scan(lines([
            user("<command-name>/model</command-name>"),
            user("Caveat: The messages below were generated by the user while running local commands."),
            user("hidden", extra: ["isMeta": true]),
            user([["type": "tool_result", "content": "ok"]]),
            user([["type": "text", "text": "add dark mode"]]),
        ]))
        #expect(details.firstPrompt == "add dark mode")
        #expect(details.hasConversation)
    }

    @Test func latestDirectoryAndBranchWin() {
        let details = SessionHistory.scan(lines([
            user("start", cwd: "/tmp/a", branch: "main"),
            assistant(cwd: "/tmp/b", branch: "feature/x"),
            assistant(cwd: "/tmp/b", branch: "HEAD"),
        ]))
        #expect(details.directory == "/tmp/b")
        #expect(details.branch == "feature/x")
    }

    @Test func endOfTranscriptWinsExceptTheFirstPrompt() {
        let tail = SessionHistory.Details(directory: "/tmp/new", branch: "dev", aiTitle: "Latest", firstPrompt: "later prompt", hasConversation: true)
        let head = SessionHistory.Details(directory: "/tmp/old", branch: "main", aiTitle: "Early", firstPrompt: "first prompt", hasConversation: true)
        let merged = tail.merged(withEarlier: head)
        #expect(merged.directory == "/tmp/new")
        #expect(merged.branch == "dev")
        #expect(merged.aiTitle == "Latest")
        #expect(merged.firstPrompt == "first prompt")
    }

    @Test func emptyAutomatedOrDirectorylessSessionsAreNotResumable() {
        let empty = SessionHistory.scan(lines([json(["type": "permission-mode", "permissionMode": "default"])]))
        #expect(SessionHistory.session(id: "a", details: empty, modified: now) == nil)

        let sdk = SessionHistory.scan(lines([json(["type": "user", "cwd": "/tmp", "entrypoint": "sdk-ts", "message": ["content": "hi"]])]))
        #expect(SessionHistory.session(id: "b", details: sdk, modified: now) == nil)

        let noDirectory = SessionHistory.Details(firstPrompt: "hi", hasConversation: true)
        #expect(SessionHistory.session(id: "c", details: noDirectory, modified: now) == nil)
    }

    @Test func tidiesTitlesToOneShortLine() {
        #expect(SessionHistory.tidy("  fix   this\nand that ") == "fix this")
        let long = SessionHistory.tidy(String(repeating: "a", count: 300))
        #expect(long.count == 120)
        #expect(long.hasSuffix("…"))
    }

    @Test func dropsPartialLinesAtChunkEdges() {
        let data = Data("tail of a line\n{\"a\":1}\n{\"b\":2}\n{\"c\":".utf8)
        let parsed = SessionHistory.lines(in: data, startsMidLine: true, endsMidLine: true)
        #expect(parsed.map { String(decoding: $0, as: UTF8.self) } == ["{\"a\":1}", "{\"b\":2}"])
    }

    // MARK: Scanning

    @Test func listsRecentSessionsNewestFirstSkippingRunningAndEmpty() throws {
        let projects = try Projects()
        let cwd = projects.workspace.path
        try projects.transcript("old", lines: [user("old work", cwd: cwd), assistant(cwd: cwd)], modified: now.addingTimeInterval(-3600))
        try projects.transcript("new", project: "-tmp-web", lines: [user("new work", cwd: cwd), assistant(cwd: cwd)], modified: now)
        try projects.transcript("running", lines: [user("live", cwd: cwd)], modified: now.addingTimeInterval(10))
        try projects.transcript("empty", lines: [json(["type": "mode", "mode": "normal"])], modified: now.addingTimeInterval(20))
        // Subagent transcripts sit in a subfolder and aren't sessions.
        try projects.transcript("agent", project: "-tmp-shop/new/subagents", lines: [user("sub", cwd: cwd)], modified: now.addingTimeInterval(30))

        let (sessions, cache) = try SessionHistory.recent(in: projects.root, limit: 3, excluding: ["running"])
        #expect(sessions.map(\.id) == ["new", "old"])
        #expect(sessions.first?.title == "new work")
        #expect(sessions.first?.directory == cwd)
        #expect(sessions.first?.updatedAt == now)
        // Read once, empty or not; the running session isn't read at all.
        #expect(cache.count == 3)
    }

    @Test func respectsTheLimitAndReusesTheCache() throws {
        let projects = try Projects()
        let cwd = projects.workspace.path
        for index in 0..<5 {
            try projects.transcript("s\(index)", lines: [user("task \(index)", cwd: cwd)], modified: now.addingTimeInterval(Double(index)))
        }
        let first = try SessionHistory.recent(in: projects.root, limit: 2)
        #expect(first.sessions.map(\.id) == ["s4", "s3"])

        // A cached entry is trusted while the file's date is unchanged.
        var cache = first.cache
        // Keyed by the listing's URLs (which resolve /var to /private/var), so look it up by name.
        let url = try #require(cache.keys.first { $0.lastPathComponent == "s4.jsonl" })
        let stale = try #require(cache[url])
        cache[url] = (stale.modified, PastSession(id: "s4", directory: cwd, title: "from cache", branch: nil, updatedAt: now))
        let second = try SessionHistory.recent(in: projects.root, limit: 2, cache: cache)
        #expect(second.sessions.first?.title == "from cache")
    }

    @Test func missingProjectsFolderIsNoSessions() throws {
        let missing = FileManager.default.temporaryDirectory.appendingPathComponent("nope-\(UUID().uuidString)")
        let result = try SessionHistory.recent(in: missing, limit: 3)
        #expect(result.sessions.isEmpty)
    }

    @Test func readsTitleFromTheEndOfALargeTranscript() throws {
        let projects = try Projects()
        let cwd = projects.workspace.path
        // Bulky tool output between the first prompt and the title, bigger than one tail read.
        let filler = json(["type": "attachment", "attachment": String(repeating: "x", count: 200_000)])
        let lines = [user("first prompt", cwd: cwd)] + Array(repeating: filler, count: 8)
            + [assistant(cwd: cwd), json(["type": "ai-title", "aiTitle": "Big session"])]
        let url = try projects.transcript("big", lines: lines, modified: now)
        let session = try #require(SessionHistory.read(url, modified: now))
        #expect(session.title == "Big session")
        #expect(session.directory == cwd)
    }

    @Test func fallsBackToTheFirstPromptAtTheStartOfALargeTranscript() throws {
        let projects = try Projects()
        let cwd = projects.workspace.path
        let filler = json(["type": "attachment", "attachment": String(repeating: "x", count: 200_000)])
        let lines = [user("the very first prompt", cwd: cwd)] + Array(repeating: filler, count: 8)
            + [user("a later prompt", cwd: cwd), assistant(cwd: cwd)]
        let url = try projects.transcript("big", lines: lines, modified: now)
        let session = try #require(SessionHistory.read(url, modified: now))
        #expect(session.title == "the very first prompt")
    }

    // MARK: Launching

    @Test func scriptResumesInTheProjectFolder() throws {
        let script = try ClaudeLauncher.script(.resume(sessionID: "0efccb8f-6970-4eab-8394-76a887f419ca"), in: "/Users/me/My Project")
        #expect(script.hasPrefix("#!/bin/sh\n"))
        #expect(script.contains("rm -f \"$0\""))
        #expect(script.contains("cd '/Users/me/My Project' ||"))
        #expect(script.contains("-l -i -c 'claude --resume 0efccb8f-6970-4eab-8394-76a887f419ca'"))
    }

    @Test func scriptStartsANewSessionWithoutAFolder() throws {
        let script = try ClaudeLauncher.script(.new, in: nil)
        #expect(!script.contains("cd "))
        #expect(script.hasSuffix("-l -i -c 'claude'\n"))
    }

    @Test func scriptQuotesAwkwardFolderNames() throws {
        let script = try ClaudeLauncher.script(.new, in: "/tmp/it's $(here)")
        #expect(script.contains("cd '/tmp/it'\\''s $(here)' ||"))
    }

    @Test func rejectsSessionIdsThatArentIds() {
        for id in ["", "abc; rm -rf ~", "$(whoami)", "a b"] {
            #expect(throws: ClaudeLauncher.LaunchError.invalidSessionID) {
                try ClaudeLauncher.script(.resume(sessionID: id), in: "/tmp")
            }
        }
    }

    @Test func agePhrases() {
        #expect(ResumeWidgetView.agePhrase(now.addingTimeInterval(-20), now: now) == "just now")
        #expect(ResumeWidgetView.agePhrase(now.addingTimeInterval(-12 * 60), now: now) == "12m ago")
        #expect(ResumeWidgetView.agePhrase(now.addingTimeInterval(-3 * 3600), now: now) == "3h ago")
        #expect(ResumeWidgetView.agePhrase(now.addingTimeInterval(-2 * 86_400), now: now) == "2d ago")
    }
}

@MainActor
@Suite("Resume monitor")
struct ResumeMonitorTests {
    private func settings() -> AppSettings {
        AppSettings(defaults: UserDefaults(suiteName: "resume-monitor-\(UUID().uuidString)")!)
    }

    private let session = PastSession(id: "abc", directory: "/tmp", title: "Fix it", branch: nil, updatedAt: .now)

    @Test func launchFailureIsShownAndClearsTheBusyState() {
        var launched: [(ClaudeLauncher.Mode, String?)] = []
        let monitor = ResumeMonitor(settings: settings()) { mode, directory, completion in
            launched.append((mode, directory))
            completion(.folderMissing("/tmp/gone"))
        }
        monitor.resume(session)
        #expect(launched.count == 1)
        #expect(launched.first?.0 == .resume(sessionID: "abc"))
        #expect(launched.first?.1 == "/tmp")
        #expect(monitor.launchError == "/tmp/gone no longer exists.")
        #expect(monitor.launching == nil)

        monitor.dismissError()
        #expect(monitor.launchError == nil)
    }

    @Test func ignoresASecondLaunchWhileOneIsUnderway() {
        var count = 0
        var pending: (@MainActor (ClaudeLauncher.LaunchError?) -> Void)?
        let monitor = ResumeMonitor(settings: settings()) { _, _, completion in
            count += 1
            pending = completion
        }
        monitor.resume(session)
        monitor.startNew(in: "/tmp")
        #expect(count == 1)
        #expect(monitor.launching == "abc")
        pending?(nil)
        #expect(monitor.launchError == nil)
    }

    @Test func turningOffClearsEverything() {
        let monitor = ResumeMonitor(settings: settings()) { _, _, completion in completion(.terminalMissing) }
        monitor.startNew(in: nil)
        #expect(monitor.launchError == "Terminal isn't installed.")
        monitor.setEnabled(false)
        #expect(!monitor.isEnabled)
        #expect(monitor.launchError == nil)
        #expect(monitor.recent.isEmpty)
    }
}
